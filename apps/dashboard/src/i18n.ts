export const DICTS: Record<Lang, Record<Key, string>> = { en, ja };

export type Params = Record<string, string | number>;

/** 言語を持つ翻訳関数。format.ts の関数は `t.lang` のロケールで Intl を使う。 */
export type T = {
  (key: Key, params?: Params): string;
  readonly lang: Lang;
};

/** 単複の形（`one|other`）を選ぶ。`|` が無い・n が無いときはそのまま。 */
function pickPlural(template: string, lang: Lang, n: Params[string] | undefined): string {
  if (typeof n !== "number" || !template.includes("|")) return template;
  const forms = template.split("|");
  const one = new Intl.PluralRules(localeOf(lang)).select(n) === "one";
  return (one ? forms[0] : forms[forms.length - 1]) ?? template;
}

export function makeT(lang: Lang): T {
  const dict = DICTS[lang];
  const t = (key: Key, params?: Params): string => {
    const template = pickPlural(dict[key], lang, params?.n);
    if (params === undefined) return template;
    // 差し込みは 1 回だけ（値の中の {name} は置き換えない）。関数で返すので $& などの置換記号も効かない
    return template.replace(/\{(\w+)\}/g, (m, name: string) =>
      Object.hasOwn(params, name) ? String(params[name]) : m,
    );
  };
  return Object.assign(t, { lang });
}

/** 言語ごとの t は作り直さない。 */
const CACHE: Partial<Record<Lang, T>> = {};
export function tFor(lang: Lang): T {
  const cached = CACHE[lang];
  if (cached !== undefined) return cached;
  const made = makeT(lang);
  CACHE[lang] = made;
  return made;
}
