// gitleaks が見つけないものを、自前の正規表現で調べる（mise run scan:secrets から呼ばれる）。
// 使い方: node scripts/scan-patterns.mjs [repoDir]
// 出力には「規則名・場所（ファイル:行・コミット）」だけを書き、見つけた値そのものは書かない。
// 終了コード: 0 = 失敗なし（参考は除く） / 1 = 許可リストに無い検出がある
import { spawnSync } from "node:child_process";
import path from "node:path";

const repo = path.resolve(process.argv[2] ?? ".");

// ---- 規則 ---------------------------------------------------------------
// kind: "fail"   = 検出したら失敗（許可リストを除く）
//       histKind = 履歴の点検だけ kind を変える（HEAD は kind のまま）
//       "review" = 参考。文書の点検（M6 の作業 5）用に件数だけ出す。失敗にしない
const RULES = [
  {
    id: "github-token",
    kind: "fail",
    re: /\b(?:gh[pousr]_[A-Za-z0-9]{16,}|github_pat_[A-Za-z0-9_]{20,})/g,
  },
  { id: "anthropic-or-openai-key", kind: "fail", re: /\bsk-(?:ant-)?[A-Za-z0-9_-]{20,}/g },
  { id: "slack-token", kind: "fail", re: /\bxox[abprs]-[A-Za-z0-9-]{10,}/g },
  { id: "jwt", kind: "fail", re: /\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]*/g },
  { id: "private-key", kind: "fail", re: /-----BEGIN [A-Z ]*PRIVATE KEY-----/g },
  { id: "bearer-header", kind: "fail", re: /Authorization:\s*Bearer\s+[A-Za-z0-9._~+/=-]{16,}/gi },
  // 32 桁の 16 進数（Cloudflare の account id など）。40 桁以上（git の SHA など）の一部は除く
  { id: "hex32-id", kind: "fail", re: /(?<![0-9A-Fa-f])[0-9A-Fa-f]{32}(?![0-9A-Fa-f])/g },
  { id: "workers-dev-host", kind: "fail", re: /(?:[A-Za-z0-9-]+\.)+workers\.dev\b/g },
  { id: "local-abs-path", kind: "fail", re: /\/Users\/[A-Za-z0-9_.-]+\//g },
  // 実際のセッション ID（8 文字以上）だけを対象にする。文書中の「claude.ai/code/session_ という文字列」の言及は含めない
  { id: "claude-session-url", kind: "fail", re: /claude\.ai\/code\/session_[A-Za-z0-9]{8,}/g },
  // 公開しない他のリポジトリの名前。名前そのものをここに書くと自分が検出されるので、実行時に組み立てる。
  // HEAD では失敗、履歴では消せないので参考（件数だけ）にする
  {
    id: "private-repo-name",
    kind: "fail",
    histKind: "review",
    re: new RegExp(
      `\\b(?:${["rovo", "mcp"].join("-")}|${["cloudflare", "infra"].join("-")})\\b`,
      "g",
    ),
  },
];

// ---- 許可リスト（小さく保つ。理由を必ず書く）-----------------------------------
// value は検出した値に対する正規表現、where は場所（ファイルのパス）に対する正規表現（どちらか、または両方）。実在の値は足さない。
const ALLOW = [
  {
    rule: "workers-dev-host",
    value: /^(?:[A-Za-z0-9-]+\.)*example\.workers\.dev$/,
    reason: "example サブドメインのプレースホルダ（デプロイ時に実 URL へ置き換える）",
  },
  {
    rule: "github-token",
    value: /^ghp_0{36}$/,
    reason: "scan:secrets の自己確認用ダミー（全桁 0）。.gitleaks.toml の許可と対応",
  },
  {
    rule: "github-token",
    value:
      /^(?:github_pat_11AAAAAAA0abcdefghijkl|gh[a-z]_(?:abcdefghijklmnop(?:qrstuvwxyz(?:0123456789)?)?|SECRETSECRETSECRETSECRET|secretvalue0123456789))$/,
    reason:
      "テストの明らかなダミー（連続したアルファベット・AAAA・SECRET・secretvalue）。マスキング処理の検証用",
  },
  {
    rule: "anthropic-or-openai-key",
    value: /^sk-abcdefghijklmnopqrstuvwxyz0123456789$/,
    reason: "テストの明らかなダミー（連続したアルファベット）。マスキング処理の検証用",
  },
  {
    rule: "slack-token",
    value: /^xox[bp]-1234567890$/,
    reason: "テストの明らかなダミー（連番）。マスキング処理の検証用",
  },
  {
    rule: "private-key",
    where: /\/test\/unit\/(?:redact|github\/app)\.test\.ts/,
    reason:
      "テスト内の PEM ヘッダだけのダミー（本体は MIIabc / AAAA の数文字）。マスキングと鍵の読み込み失敗の検証用",
  },
  {
    rule: "bearer-header",
    value: /^Authorization: Bearer abc\.DEF-123_xyz==$/,
    reason: "テストの明らかなダミー。マスキング処理の検証用",
  },
  {
    rule: "hex32-id",
    where: /worker-configuration\.d\.ts/,
    line: /^\/\/ Generated by Wrangler by running `wrangler types[^`]*` \(hash: [0-9a-f]{32}\)$/,
    reason:
      "wrangler types が生成する型ファイルの先頭コメントの hash（アカウント ID ではない）。場所と行の形の両方が合うときだけ許可する",
  },
];

// 追跡されてはいけないパス（現在と履歴の両方）
const FORBIDDEN_PATHS = [
  {
    re: /^\.claude\//,
    allow: /^\.claude\/settings\.json$/,
    why: ".claude/ は追跡しない（settings.json だけ可。settings.local.json や handover は手元のファイル）",
  },
  {
    re: /(^|\/)\.dev\.vars(\.[^/]*)?$/,
    allow: /\.dev\.vars\.example$/,
    why: ".dev.vars は追跡しない（.example だけ可）",
  },
  { re: /(^|\/)(dist|\.wrangler)\//, why: "ビルド成果物・wrangler のローカル状態は追跡しない" },
  { re: /(^|\/)\.env(\.|$)/, why: ".env は追跡しない" },
];

// Claude-Session トレーラーを持つコミット数の上限。2026-10-20 に git filter-repo で履歴を書き換え済みなので 0
// （phase7.md D2 案 b）。1 本でもあれば失敗にする。
const SESSION_COMMITS_MAX = 0;

// ---- 実装 ---------------------------------------------------------------
function git(args, opts = {}) {
  const r = spawnSync("git", ["-C", repo, ...args], {
    maxBuffer: 1 << 30,
    encoding: "utf8",
    ...opts,
  });
  if (r.status !== 0) {
    console.error(`git ${args.join(" ")} が失敗しました: ${r.stderr}`);
    process.exit(2);
  }
  return r.stdout;
}

function scanLine(line, loc, out) {
  for (const rule of RULES) {
    rule.re.lastIndex = 0;
    for (const m of line.matchAll(rule.re)) {
      const allowed = ALLOW.find(
        (a) =>
          a.rule === rule.id &&
          (!a.value || a.value.test(m[0])) &&
          (!a.where || a.where.test(loc.where)) &&
          (!a.line || a.line.test(line)),
      );
      out.push({ rule: rule.id, allowed: allowed?.reason ?? null, ...loc });
    }
  }
}

function forbidden(p) {
  return FORBIDDEN_PATHS.find((f) => f.re.test(p) && !f.allow?.test(p));
}

// HEAD
const head = [];
const headForbidden = [];
const files = git(["ls-tree", "-r", "-z", "--name-only", "HEAD"]).split("\0").filter(Boolean);
for (const f of files) {
  const fb = forbidden(f);
  if (fb) headForbidden.push({ file: f, why: fb.why });
  const r = spawnSync("git", ["-C", repo, "show", `HEAD:${f}`], { maxBuffer: 1 << 29 });
  if (r.status !== 0 || r.stdout.includes(0)) continue; // バイナリは除く
  r.stdout
    .toString("utf8")
    .split("\n")
    .forEach((line, i) => {
      scanLine(line, { where: `${f}:${i + 1}` }, head);
    });
}

// 全履歴（全ブランチ・全タグ。削除された内容を含む。コミットメッセージも対象）
const hist = [];
const histForbidden = new Map();
const log = git(["log", "--all", "-p", "-U0", "--no-color", "--format=@@COMMIT %h%n%B%n@@ENDMSG"]);
let commit = "";
let file = "";
let inMsg = false;
for (const line of log.split("\n")) {
  if (line.startsWith("@@COMMIT ")) {
    commit = line.slice(9);
    file = "(message)";
    inMsg = true;
    continue;
  }
  if (inMsg) {
    if (line === "@@ENDMSG") inMsg = false;
    else scanLine(line, { where: `${commit} (コミットメッセージ)`, commit, inMessage: true }, hist);
    continue;
  }
  if (line.startsWith("+++ b/") || line.startsWith("--- a/")) {
    file = line.slice(6);
    const fb = forbidden(file);
    if (fb) histForbidden.set(`${commit}:${file}`, { commit, file, why: fb.why });
    continue;
  }
  if (line.startsWith("+++ ") || line.startsWith("--- ")) continue; // /dev/null
  if (line[0] === "+" || line[0] === "-")
    scanLine(line.slice(1), { where: `${commit} ${file}`, commit }, hist);
}
const allCommits = git(["rev-list", "--all", "--count"]).trim();

// ---- 集計と出力 -----------------------------------------------------------
let failed = false;
const fmtLoc = (xs, n = 5) => {
  const w = [...new Set(xs.map((x) => x.where))];
  return `${w.slice(0, n).join(", ")}${w.length > n ? ` ほか ${w.length - n} 件` : ""}`;
};

function report(title, hits, fbs, scope) {
  console.log(`\n== ${title} ==`);
  for (const base of RULES) {
    const rule = { ...base, kind: (scope === "hist" && base.histKind) || base.kind };
    const rs = hits.filter((h) => h.rule === rule.id);
    const bad = rs.filter((h) => !h.allowed);
    const ok = rs.filter((h) => h.allowed);
    const tag = rule.kind === "fail" ? "" : " [参考]";
    console.log(`${rule.id}${tag}: 検出 ${bad.length} 件 / 許可 ${ok.length} 件`);
    if (bad.length) console.log(`    場所: ${fmtLoc(bad)}`);
    if (ok.length)
      console.log(`    許可の理由: ${[...new Set(ok.map((h) => h.allowed))].join(" / ")}`);
    if (rule.kind === "fail" && bad.length) failed = true;
  }
  console.log(`追跡禁止パス: ${fbs.length} 件`);
  for (const f of fbs.slice(0, 10))
    console.log(`    ${f.commit ? `${f.commit} ` : ""}${f.file}: ${f.why}`);
  if (fbs.length) failed = true;
}

report("HEAD", head, headForbidden, "head");
report(
  `全履歴（git log -p --all。${allCommits} コミット）`,
  hist,
  [...histForbidden.values()],
  "hist",
);

// Claude-Session は、1 本でもあれば失敗（上限 0）。件数を上限と比べる
const sess = hist.filter((h) => h.rule === "claude-session-url");
const sessCommits = new Set(sess.map((h) => h.commit));
const sessOutsideMsg = sess.filter((h) => !h.inMessage);
const sessInHead = head.filter((h) => h.rule === "claude-session-url");
console.log(
  `\nClaude-Session: ${sessCommits.size} コミット（上限 ${SESSION_COMMITS_MAX}。履歴は 2026-10-20 に書き換え済み）`,
);
if (sessInHead.length) {
  console.log(`    HEAD のファイルに存在: ${fmtLoc(sessInHead)}`);
  failed = true;
}
if (sessOutsideMsg.length) {
  console.log(`    メッセージ以外に存在: ${fmtLoc(sessOutsideMsg)}`);
  failed = true;
}
if (sessCommits.size > SESSION_COMMITS_MAX) {
  console.log("    上限 0 を超えている（Claude-Session を付けない決定: phase7.md D2）");
  failed = true;
}

console.log(
  failed
    ? "\nscan-patterns: 失敗（上の検出を確認する）"
    : "\nscan-patterns: OK（許可・参考を除いて 0 件）",
);
process.exit(failed ? 1 : 0);
