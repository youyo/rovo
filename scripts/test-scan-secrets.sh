#!/usr/bin/env bash
# scan:secrets の自己確認。ダミーの秘密を入れた一時的な git リポジトリで次を確かめる。
#  (a) ダミーの秘密を HEAD でも履歴（削除済み）でも検出して失敗すること
#  (b) 許可リストのダミーだけなら 0 件で通ること
#  (c) Claude-Session は 1 本でもコミットメッセージにあれば失敗にすること（上限 0）
# ダミーは実行時に組み立てる（このファイル自体が点検で引っかからないように）。
set -uo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
scan="$here/scan-secrets.sh"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail=0

mk() { # mk <dir>
  git init -q "$1"
  git -C "$1" config user.email test@example.com
  git -C "$1" config user.name test
  git -C "$1" config commit.gpgsign false
}
commit() { git -C "$1" add -f -- . && git -C "$1" commit -q --no-verify -m "$2" -m "$3"; }
expect() { # expect <名前> <期待する終了コード> <実際>
  if [ "$2" = "$3" ]; then echo "ok   $1"; else echo "NG   $1 (期待 $2 / 実際 $3)"; fail=1; fi
}

pat="gh""p_"                      # GitHub PAT の接頭辞
real="${pat}Zx8Qw3Lk9Pm2Vn7Rt4Yb6Hc1Df5Gj0Ks3AaB"     # ダミー（実在しない）
ok_dummy="${pat}$(printf '0%.0s' $(seq 36))"        # 許可リストのダミー
sess="https://claude.ai/code/""session_0123456789abcdef"
hex32="0123456789abcdef""0123456789abcdef"   # 32 桁の 16 進数（account id の形）
wdev="someone.workers"".dev"
upath="/Users""/alice/x"
repo_a="rovo""-mcp"                              # 公開しない他のリポジトリの名前

# (a) HEAD にある秘密
mk "$work/a"
echo "token = $real" > "$work/a/f.txt"
commit "$work/a" "add" "x"
"$scan" "$work/a" >/dev/null 2>&1; expect "(a1) HEAD の秘密を検出して失敗する" 1 $?

# (a) 履歴にだけある秘密（削除済み）、個人の値
mk "$work/b"
printf 'id = %s\nhost = %s\np = %s\n' "$hex32" "$wdev" "$upath" > "$work/b/f.txt"
commit "$work/b" "add" "x"
git -C "$work/b" rm -q f.txt && echo ok > "$work/b/g.txt" && commit "$work/b" "rm" "x"
"$scan" "$work/b" >/dev/null 2>&1; expect "(a2) 削除済みの秘密・個人の値を履歴から検出して失敗する" 1 $?

# (b) 許可リストのダミーだけ
mk "$work/c"
echo "token = $ok_dummy" > "$work/c/f.txt"
echo "h = rovo.example.workers.dev" >> "$work/c/f.txt"
commit "$work/c" "add" "x"
"$scan" "$work/c" >/dev/null 2>&1; expect "(b) 許可リストのダミーは検出しない" 0 $?

# (c) Claude-Session は上限 0（1 本でもあれば失敗）
mk "$work/d"
echo hello > "$work/d/f.txt"
commit "$work/d" "add" "Claude-Session: $sess"
out="$("$scan" "$work/d" 2>&1)"; rc=$?
expect "(c1) メッセージに Claude-Session が 1 本でもあれば失敗にする" 1 $rc
echo "$out" | grep -q "上限 0" ; expect "(c2) 上限 0 として表示する" 0 $?
echo "$out" | grep -q "既知" ; expect "(c4) 既知の扱いはしない" 1 $?
mk "$work/m"
echo hello > "$work/m/f.txt"
commit "$work/m" "add" "x"
"$scan" "$work/m" >/dev/null 2>&1; expect "(c5) Claude-Session が 0 本なら通る" 0 $?

# (c) Claude-Session がファイルに入っていたら失敗
mk "$work/e"
echo "see $sess" > "$work/e/f.txt"
commit "$work/e" "add" "x"
"$scan" "$work/e" >/dev/null 2>&1; expect "(c3) ファイル中の Claude-Session は失敗にする" 1 $?

# (d) scripts/ と設定がコミットされても、自分自身を検出しない（ダミーのリテラルを書いてしまう事故の防止）
mk "$work/f"
mkdir -p "$work/f/scripts"
cp "$here"/* "$work/f/scripts/"
cp "$here/../.gitleaks.toml" "$work/f/"
commit "$work/f" "add scripts" "x"
"$scan" "$work/f" >/dev/null 2>&1; expect "(d) scripts/ をコミットしても検出されない" 0 $?

# (e) hex32 の許可は場所と行の形の両方が合うときだけ
gen="// Generated by Wrangler by running \`wrangler types --strict-vars=false\` (hash: ${hex32})"
mk "$work/g"
mkdir -p "$work/g/apps/web"
printf '%s\n' "$gen" > "$work/g/apps/web/worker-configuration.d.ts"
commit "$work/g" "add" "x"
"$scan" "$work/g" >/dev/null 2>&1; expect "(e1) 生成コメントの hash は許可する" 0 $?
mk "$work/h"
mkdir -p "$work/h/apps/web"
printf '%s\nconst accountId = "%s";\n' "$gen" "$hex32" > "$work/h/apps/web/worker-configuration.d.ts"
commit "$work/h" "add" "x"
"$scan" "$work/h" >/dev/null 2>&1; expect "(e2) 同じファイルでも別の行の 32 桁は検出する" 1 $?

# (f) .claude/ は settings.json だけ追跡してよい
mk "$work/i"
mkdir -p "$work/i/.claude"
echo '{}' > "$work/i/.claude/settings.json"
commit "$work/i" "add" "x"
"$scan" "$work/i" >/dev/null 2>&1; expect "(f1) .claude/settings.json は許可する" 0 $?
mk "$work/j"
mkdir -p "$work/j/.claude"
echo '{}' > "$work/j/.claude/settings.local.json"
commit "$work/j" "add" "x"
"$scan" "$work/j" >/dev/null 2>&1; expect "(f2) .claude/settings.local.json は失敗にする" 1 $?

# (g) 公開しない他のリポジトリの名前: HEAD は失敗、履歴だけなら参考
mk "$work/k"
echo "deploy from $repo_a" > "$work/k/f.txt"
commit "$work/k" "add" "x"
"$scan" "$work/k" >/dev/null 2>&1; expect "(g1) HEAD にある他のリポジトリ名は失敗にする" 1 $?
mk "$work/l"
echo "deploy from $repo_a" > "$work/l/f.txt"
commit "$work/l" "add" "x"
echo "deploy from downstream" > "$work/l/f.txt"
commit "$work/l" "fix" "x"
"$scan" "$work/l" >/dev/null 2>&1; expect "(g2) 履歴だけにある他のリポジトリ名は参考（失敗にしない）" 0 $?

# (h) --gitleaks-only: 下流（private）の CI 用。gitleaks だけを流し、scan-patterns 専用の対象では失敗しない
gl=("$scan" --gitleaks-only)
"${gl[@]}" "$work/a" >/dev/null 2>&1; expect "(h1) --gitleaks-only: HEAD の秘密を検出して失敗する" 1 $?
"${gl[@]}" "$work/b" >/dev/null 2>&1; expect "(h2) --gitleaks-only: account id・workers.dev・絶対パスは検出しない（履歴にあっても）" 0 $?
"${gl[@]}" "$work/k" >/dev/null 2>&1; expect "(h3) --gitleaks-only: 他のリポジトリ名は検出しない" 0 $?
"${gl[@]}" "$work/d" >/dev/null 2>&1; expect "(h4) --gitleaks-only: Claude-Session は検出しない" 0 $?
mk "$work/n"
echo "token = $real" > "$work/n/f.txt"
commit "$work/n" "add" "x"
git -C "$work/n" rm -q f.txt && echo ok > "$work/n/g.txt" && commit "$work/n" "rm" "x"
"${gl[@]}" "$work/n" >/dev/null 2>&1; expect "(h5) --gitleaks-only: 履歴にだけある秘密を検出して失敗する" 1 $?
out="$("${gl[@]}" "$work/b" 2>&1)"
echo "$out" | grep -q "自前の正規表現"; expect "(h6) --gitleaks-only: 自前の正規表現は流さない" 1 $?

# (i) upstream 専用のワークフローは youyo/rovo でだけ動く（下流に取り込まれても止まる）
wf="$here/../.github/workflows"
job_if() { awk -v job="  $2:" '$0==job{f=1;next} f&&/^  [a-z]/{f=0} f&&/^    if:/{print}' "$wf/$1"; }
job_if sketio-arch.yml arch | grep -q "github.repository == 'youyo/rovo'"; expect "(i1) architecture の arch ジョブは upstream だけで動く" 0 $?
job_if ci.yml patterns | grep -q "github.repository == 'youyo/rovo'"; expect "(i2) ci の patterns ジョブ（公開点検）は upstream だけで動く" 0 $?
job_if ci.yml secrets | grep -q "if:"; expect "(i3) ci の secrets ジョブ（gitleaks）には条件を付けない（下流でも動く）" 1 $?
grep -q "scan:gitleaks" "$wf/ci.yml"; expect "(i4) ci は gitleaks だけの経路（scan:gitleaks）を使う" 0 $?

exit "$fail"
